#!/usr/bin/env python3
"""Writes hooks/wear-icons.ts: every pictured item at 1x (half its size), for the mod's wardrobe cards.

The pictures in hooks/wear-*.ts are 2x, for the desktop app. The details pane shows an item on a 46x32
card, and the desktop drops a pane whose pictures weigh too much, so the mod's cards take these instead.
Run it again whenever hooks/wear-*.ts change: python3 scripts/wear-icons.py (needs Pillow).
"""
import base64
import io
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ITEM = re.compile(r"^  (\w+): \{ w: (\d+), h: (\d+), uri: webp\(\n((?:    '[^']*',?\n)+)  \) \},?$", re.M)

icons = []
for part in sorted((ROOT / 'hooks').glob('wear-[0-9].ts')):
    for name, w, h, lines in ITEM.findall(part.read_text()):
        data = base64.b64decode(''.join(re.findall(r"'([^']*)'", lines)))
        img = Image.open(io.BytesIO(data)).convert('RGBA')
        small = img.resize((max(1, round(int(w) / 2)), max(1, round(int(h) / 2))), Image.LANCZOS)
        out = io.BytesIO()
        small.save(out, 'WEBP', quality=80, method=6)
        b64 = base64.b64encode(out.getvalue()).decode()
        chunks = [b64[i:i + 100] for i in range(0, len(b64), 100)]
        icons.append((name, chunks))

assert icons, 'no pictures found in hooks/wear-*.ts'
HEAD = """// Generated by scripts/wear-icons.py from hooks/wear-*.ts: every pictured item at 1x (half its size), for the
// mod's wardrobe cards; the 2x pictures stay for the desktop app and for Mochi as drawn."""
# Two parts, so that no file is too large for the plugin directory to read whole (as wear-1.ts to wear-4.ts are split).
half = (len(icons) + 1) // 2
for n, part in ((1, icons[:half]), (2, icons[half:])):
    body = '\n'.join(f"  {name}: webp(\n" + '\n'.join(f"    '{c}'," for c in chunks) + '\n  ),' for name, chunks in part)
    (ROOT / 'hooks' / f'wear-icons-{n}.ts').write_text(f"""{HEAD}

import type {{ Item }} from '../types'
import {{ webp }} from './assets'

export const WEAR_ICON_{n}: Partial<Record<Item, string>> = {{
{body}
}}
""")
(ROOT / 'hooks' / 'wear-icons.ts').write_text(f"""{HEAD}

import type {{ Item }} from '../types'
import {{ WEAR_ICON_1 }} from './wear-icons-1'
import {{ WEAR_ICON_2 }} from './wear-icons-2'

export const WEAR_ICON: Partial<Record<Item, string>> = {{ ...WEAR_ICON_1, ...WEAR_ICON_2 }}
""")
print(f'{len(icons)} icons')
