/** Polish plural form: 1 plik, 2 pliki, 5 plików; 12–14 and 21, 25… take the "many" form. */
const form = (n: number, one: string, few: string, many: string) => {
  if (n === 1) return one
  const a = Math.abs(n) % 100
  const b = a % 10
  return b >= 2 && b <= 4 && (a < 12 || a > 14) ? few : many
}

/** Number plus its noun; a formatted number ("1 234") is read by its digits. */
const count = (n: number | string, one: string, few: string, many: string) =>
  `${n} ${form(typeof n === 'number' ? n : Number(n.replace(/\D/g, '')) || 0, one, few, many)}`

