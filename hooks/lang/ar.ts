/** A noun's forms after a number: one, two, 3–10, 11–99, and 100, 101, 102… */
type Noun = readonly [one: string, two: string, few: string, many: string, other: string]

/**
 * Number plus its noun, the Arabic way: 1 and 2 are said by the noun alone (ملف واحد, ملفان),
 * 0 and 3–10 take the plural (3 ملفات), 11–99 the singular accusative (11 ملفًا), and 100, 101, 102… the
 * plain singular (100 ملف). A formatted number ("1,234") is read by its digits.
 */
const count = (v: number | string, [one, two, few, many, other]: Noun) => {
  const n = typeof v === 'number' ? v : Number(v.replace(/\D/g, '')) || 0
  if (n === 1) return one
  if (n === 2) return two
  const r = n % 100
  return `${v} ${n === 0 || (r >= 3 && r <= 10) ? few : r >= 11 ? many : other}`
}

